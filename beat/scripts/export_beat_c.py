"""Export madmom's online beat tracker (one net) for the C port in jank (core/beat/), and the reference results.

  model   write beat_model.c / beat_model.h (the log filterbank, sparse: madmom's code, BSD-3) and beat_weights.bin, the
          network's weights blob (core/beat/beat_weights.h) of madmom.models.BEATS_LSTM[0] or --weights, float32 (madmom's
          pickle is float32 already: no loss). The weights never go into the source: the firmware reads the blob from its
          "beatw" flash partition (madmom's: CC BY-NC-SA 4.0, for the user's own device only, never to be shipped)
  prep    audio -> mono 44.1 kHz float32 WAV (soxr, as eval/trackers.py does), the file both sides read
  ref     for each prepared WAV: features (npy, scratch only), the net's activation (text), the DBN's beats
          (text) and the ModeBpm trace (text); the DBN is madmom's online forward algorithm, 90-180 BPM,
          the other parameters as madmom's defaults (transition 100, observation 16, fps 100)

  .venv/bin/python -I scripts/export_beat_c.py model OUT_DIR [--weights ours.pt]
  .venv/bin/python -I scripts/export_beat_c.py prep OUT_DIR IN.wav...
  .venv/bin/python -I scripts/export_beat_c.py ref  OUT_DIR PREPARED.wav... [--weights ours.pt]

--weights FILE.pt: our own net (train/train.py checkpoint or state_dict) instead of madmom's BEATS_LSTM[0]; the input
normalisation is folded into layer 0, so the C core is unchanged. The filterbank is madmom's front end either way.
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

FPS = 100
MIN_BPM, MAX_BPM = 90.0, 180.0
GATES = ("input_gate", "forget_gate", "cell", "output_gate")
sys.path.insert(0, str(REPO / "train"))
WEIGHTS: str | None = None      # --weights: ours.pt


def _our_model():
    import torch

    from peeplstm import BeatNet
    s = torch.load(WEIGHTS, weights_only=False)
    m = BeatNet()
    m.load_state_dict(s["model"] if "model" in s else s)
    return m.eval()


def _layer_arrays() -> list[dict]:
    """Per layer w[gate][in][25], r, b, p, then the output layer: madmom's, or ours (--weights)."""
    from convert import madmom_to_arrays, torch_to_arrays
    return torch_to_arrays(_our_model()) if WEIGHTS else madmom_to_arrays(_net())


def _activation(feats: np.ndarray) -> np.ndarray:
    if WEIGHTS:
        import torch
        with torch.no_grad():
            return _our_model()(torch.from_numpy(np.ascontiguousarray(feats, dtype=np.float32))[None])[0].numpy()
    return np.asarray(_net().process(feats, reset=True)).ravel()


def _net():
    from madmom.ml.nn import NeuralNetwork
    from madmom.models import BEATS_LSTM
    return NeuralNetwork.load(BEATS_LSTM[0])


def _lit(v: float) -> str:
    s = f"{v:.9g}"
    return (s if any(c in s for c in ".en") else s + ".0") + "f"      # 9 digits round-trip a float32


def _floats(name: str, a: np.ndarray) -> str:
    flat = np.ascontiguousarray(a, dtype=np.float32).ravel()
    rows = [", ".join(_lit(v) for v in flat[i:i + 8]) for i in range(0, flat.size, 8)]
    return f"const float {name}[{flat.size}] = {{\n    " + ",\n    ".join(rows) + ",\n};\n\n"


def _filterbank():
    from madmom.audio.filters import LogarithmicFilterbank
    freqs = np.fft.rfftfreq(2048, 1 / 44100)[:1024]
    fb = LogarithmicFilterbank(freqs, num_bands=12, fmin=30, fmax=17000, norm_filters=True)
    return np.asarray(fb, dtype=np.float32)


def cmd_model(out: Path) -> None:
    out.mkdir(parents=True, exist_ok=True)
    fb = _filterbank()
    starts, lens, vals = [], [], []
    for j in range(fb.shape[1]):
        nz = np.nonzero(fb[:, j])[0]
        assert nz.size == nz[-1] - nz[0] + 1, f"filter {j} is not contiguous"
        starts.append(int(nz[0]))
        lens.append(int(nz.size))
        vals.append(fb[nz[0]:nz[-1] + 1, j])
    vals = np.concatenate(vals)
    arr = _layer_arrays()
    src = (f"{Path(WEIGHTS).name}: our own net, trained by beat-listener/train (data and licence: models/LICENSE.md)"
           if WEIGHTS else "madmom.models.BEATS_LSTM[0]")
    body = ["/* Generated by beat-listener/scripts/export_beat_c.py: do not edit. The log filterbank of madmom's front end\n"
            " * (madmom's code, BSD-3). The network's weights are not here: core/beat/beat_weights.h. */\n"
            '#include "beat_model.h"\n\n']
    body.append(f"const uint16_t beat_fb_start[BEAT_BANDS] = {{{', '.join(map(str, starts))}}};\n")
    body.append(f"const uint16_t beat_fb_len[BEAT_BANDS] = {{{', '.join(map(str, lens))}}};\n")
    body.append(_floats("beat_fb_val", vals))
    (out / "beat_model.c").write_text("".join(body))
    flat = []
    for i, layer in enumerate(arr[:3]):
        n_in = layer["w"].shape[1]
        assert layer["w"].shape == (4, n_in, 25) and layer["r"].shape == (4, 25, 25)
        flat += [layer["w"], layer["r"], layer["b"], layer["p"]]      # [gate][in][25], [gate][prev][25], [gate][25], p
    flat += [arr[3]["out_w"], arr[3]["out_b"]]
    w = np.concatenate([np.ascontiguousarray(a, dtype="<f4").ravel() for a in flat]).astype("<f4").tobytes()
    import struct
    import zlib
    (out / "beat_weights.bin").write_bytes(b"JBW1" + struct.pack("<III", len(w) // 4, zlib.crc32(w), 0) + w)
    print(f"wrote {out}/beat_weights.bin: {len(w) // 4} weights from {src}")
    (out / "beat_model.h").write_text(
        "/* Generated by beat-listener/scripts/export_beat_c.py: do not edit. float32, row-major.\n"
        " * LSTM layer i: _w[gate][in][25], _r[gate][prev][25], _b[gate][25], _p[3][25] (peepholes of input, forget and\n"
        " * output gate); gates in the order input, forget, cell, output. */\n"
        "#ifndef BEAT_MODEL_H\n#define BEAT_MODEL_H\n#include <stdint.h>\n\n"
        f"#define BEAT_BANDS {fb.shape[1]}\n#define BEAT_BINS {fb.shape[0]}\n#define BEAT_FB_NNZ {vals.size}\n"
        "#define BEAT_HIDDEN 25\n#define BEAT_INPUTS (2 * BEAT_BANDS)\n\n"
        "extern const uint16_t beat_fb_start[BEAT_BANDS], beat_fb_len[BEAT_BANDS];\n"
        "extern const float beat_fb_val[BEAT_FB_NNZ];\n"
        "/* The network's weights are not in the source: they point into the weights blob (beat_weights.h), NULL until bound.\n"
        " * l0_w [4][162][25], l0_r [4][25][25], l1_w / l1_r / l2_w / l2_r [4][25][25], each b [4][25], each p [3][25], out_w [25],\n"
        " * out_b [1]. */\n"
        "extern const float *beat_l0_w, *beat_l0_r, *beat_l0_b, *beat_l0_p;\n"
        "extern const float *beat_l1_w, *beat_l1_r, *beat_l1_b, *beat_l1_p;\n"
        "extern const float *beat_l2_w, *beat_l2_r, *beat_l2_b, *beat_l2_p;\n"
        "extern const float *beat_out_w, *beat_out_b;\n\n#endif\n")
    print(f"wrote {out}/beat_model.[ch]: {vals.size} filter values")


def cmd_prep(out: Path, files: list[str]) -> None:
    import soundfile as sf
    import soxr
    out.mkdir(parents=True, exist_ok=True)
    for f in files:
        y, sr = sf.read(f, dtype="float32", always_2d=True)
        y = y.mean(axis=1)
        if sr != 44100:
            y = soxr.resample(y, sr, 44100)
        sf.write(str(out / (Path(f).stem + ".44k.wav")), y.astype(np.float32), 44100, subtype="FLOAT")
        print(f"{f}: {sr} Hz -> 44100 Hz, {y.size / 44100:.1f} s")


def _features_and_activation(y: np.ndarray):
    from madmom.audio.signal import Signal
    from madmom.audio.spectrogram import (FilteredSpectrogramProcessor, LogarithmicSpectrogramProcessor,
                                          SpectrogramDifferenceProcessor)
    from madmom.audio.signal import FramedSignalProcessor
    from madmom.audio.stft import ShortTimeFourierTransformProcessor
    from madmom.processors import SequentialProcessor
    sig = Signal(y, sample_rate=44100, num_channels=1)
    chain = SequentialProcessor((
        FramedSignalProcessor(frame_size=2048), ShortTimeFourierTransformProcessor(),
        FilteredSpectrogramProcessor(num_bands=12, fmin=30, fmax=17000, norm_filters=True),
        LogarithmicSpectrogramProcessor(mul=1, add=1),
        SpectrogramDifferenceProcessor(diff_ratio=0.5, positive_diffs=True, stack_diffs=np.hstack)))
    feats = np.asarray(chain(sig))
    return feats, _activation(feats)


def cmd_ref(out: Path, files: list[str]) -> None:
    import soundfile as sf
    from madmom.features.beats import DBNBeatTrackingProcessor, RNNBeatProcessor
    from madmom.models import BEATS_LSTM
    from eval.mode_bpm import ModeBpm
    out.mkdir(parents=True, exist_ok=True)
    rnn = RNNBeatProcessor(online=True, nn_files=[BEATS_LSTM[0]])
    for f in files:
        name = Path(f).name.replace(".44k.wav", "")
        y, sr = sf.read(f, dtype="float32", always_2d=False)
        assert sr == 44100 and y.ndim == 1
        feats, act = _features_and_activation(y)
        from madmom.audio.signal import Signal
        act2 = np.asarray(rnn(Signal(y, sample_rate=44100, num_channels=1)))
        if not WEIGHTS:
            assert np.allclose(act, act2, atol=1e-6), "feature chain differs from RNNBeatProcessor"
        else:
            act2 = act
        dbn = DBNBeatTrackingProcessor(min_bpm=MIN_BPM, max_bpm=MAX_BPM, fps=FPS, online=True)
        beats = np.asarray(dbn.process_online(act2, reset=True))
        np.save(out / f"{name}.feats.npy", feats)           # scratch use only (debugging the C front end)
        np.savetxt(out / f"{name}.act.txt", act2, fmt="%.7g")
        np.savetxt(out / f"{name}.beats.txt", beats, fmt="%.2f")
        est = ModeBpm()
        lines = []
        for t in beats:
            est.update(float(t))
            bpm = est.bpm_at(float(t))
            lines.append(f"{t:.2f} {est.mode} {-1.0 if bpm is None else bpm:.6f}")
        (out / f"{name}.mode.txt").write_text("\n".join(lines) + "\n")
        print(f"{name}: {len(act)} frames, {len(beats)} beats, final {lines[-1] if lines else '-'}")


def main() -> None:
    global WEIGHTS
    argv = sys.argv[1:]
    if "--weights" in argv:
        i = argv.index("--weights")
        WEIGHTS = argv[i + 1]
        del argv[i:i + 2]
    cmd, rest = argv[0], argv[1:]
    if cmd == "model":
        cmd_model(Path(rest[0]))
    elif cmd == "prep":
        cmd_prep(Path(rest[0]), rest[1:])
    elif cmd == "ref":
        cmd_ref(Path(rest[0]), rest[1:])
    else:
        raise SystemExit(__doc__)


if __name__ == "__main__":
    main()
