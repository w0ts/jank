"""The downbeat estimator's weights as a C table for the device (jank core/beat/down_model.[ch]).

From studies/downbeat/results/v2_weights.json (the second study's export, live/downbeat.py reads the same file): the 88
weights w[f * 4 + p] as float32, the memory in bars and the move policy. The header carries the weights' provenance.

    .venv/bin/python scripts/export_down_c.py OUT_DIR [--weights studies/downbeat/results/v2_weights.json]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))


def main() -> None:
    from live.downbeat import FEATURES, WEIGHTS, load_model
    ap = argparse.ArgumentParser()
    ap.add_argument("out", type=Path)
    ap.add_argument("--weights", type=Path, default=WEIGHTS)
    a = ap.parse_args()
    raw = a.weights.read_bytes()
    d = json.loads(raw)
    m = load_model(a.weights)                    # checks the features, the delay and the size
    sha = hashlib.sha256(raw).hexdigest()[:16]
    prov = (" * Provenance: " + d["about"] + ".\n * Trained on: " + d["trained_on"] + ".\n"
            " * The training labels are the user's own Traktor beat grids, the features come from the user's own audio\n"
            " * through the tracker's filterbank; madmom's downbeat tracker was used only as a measuring instrument (to\n"
            " * check labels), none of its output or weights is in this table.\n"
            f" * Source: beat/studies/downbeat/results/v2_weights.json (sha256 {sha}...), exported by\n"
            " * beat/scripts/export_down_c.py.\n")
    h = ("/* Generated by beat-listener/scripts/export_down_c.py: do not edit. The downbeat estimator's weights (jb_down.h).\n"
         + prov + " */\n#ifndef DOWN_MODEL_H\n#define DOWN_MODEL_H\n\n"
         f"#define DOWN_FEATURES {len(FEATURES)}\n"
         f"#define DOWN_BARS {m.bars:.1f}f              /* the accumulators' memory: exp(-1 / DOWN_BARS) a bar */\n"
         f"#define DOWN_COMMIT {m.commit:.1f}f            /* the first move: the best phase leads the second by this */\n"
         f"#define DOWN_SWITCH {m.switch:.1f}f            /* a later move: another phase leads by this ... */\n"
         f"#define DOWN_HOLD {m.hold}                  /* ... for this many beats in a row */\n\n"
         "/* w[f * 4 + p]: feature f (jb_down.h's order) at bar position p from the candidate 1 */\n"
         "extern const float down_w[DOWN_FEATURES * 4];\n\n#endif\n")
    rows = []
    for f, name in enumerate(FEATURES):
        rows.append("    " + ", ".join(f"{float(x):.9g}f" for x in m.w[f * 4:f * 4 + 4]) + f",   /* {name} */")
    c = ("/* Generated by beat-listener/scripts/export_down_c.py: do not edit. The downbeat estimator's weights.\n"
         + prov + " */\n#include \"down_model.h\"\n\nconst float down_w[DOWN_FEATURES * 4] = {\n" + "\n".join(rows) + "\n};\n")
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / "down_model.h").write_text(h)
    (a.out / "down_model.c").write_text(c)
    print(f"wrote {a.out / 'down_model.h'} and down_model.c: {len(m.w)} weights, sha256 {sha}")


if __name__ == "__main__":
    main()
