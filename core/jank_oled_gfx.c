/* a character the font lacks draws as a space (FONT[ch] || FONT[' ']) but keeps its own width */
static const uint8_t *rows_of(char ch)
{
    for (size_t i = 0; i < sizeof FONT / sizeof FONT[0]; i++)
        if (FONT[i].ch == ch)
            return FONT[i].rows;
    return FONT[0].rows;
}

static int narrow(char ch) { return ch == '.' || ch == ':' || ch == ','; }
static int adv(char ch) { return narrow(ch) ? 3 : ch == ' ' ? 4 : 6; }

int jo_text_w(const char *s, int sc)
{
    int w = 0;
    for (; *s; s++)
        w += adv(*s) * sc;
    return w - sc > 0 ? w - sc : 0;
}

void jo_text(uint8_t *fb, const char *s, int x, int y, int sc, int v)
{
    int cx = x;
    for (; *s; s++) {
        const uint8_t *g = rows_of(*s);
        int off = narrow(*s);
        for (int r = 0; r < 7; r++)
            for (int c = 0; c < 5; c++)
                if (g[r] & (0x10u >> c))
                    jo_rect(fb, cx + (c - off) * sc, y + r * sc, sc, sc, v);
        cx += adv(*s) * sc;
    }
}

void jo_text_r(uint8_t *fb, const char *s, int xr, int y, int sc, int v) { jo_text(fb, s, xr - jo_text_w(s, sc), y, sc, v); }

void jo_text_c(uint8_t *fb, const char *s, int y, int sc, int v)
{
    jo_text(fb, s, jo_iround((double)(jo_gw - jo_text_w(s, sc)) / 2.0), y, sc, v);
}

void jo_icon(uint8_t *fb, const char *const *rows, int n, int x, int y)
{
    for (int j = 0; j < n; j++)
        for (int i = 0; rows[j][i]; i++)
            if (rows[j][i] == '#')
                jo_px(fb, x + i, y + j, 1);
}

/* ---- the ink plane (jo_draw_lcd2) ---- */
static const uint8_t *s_ink_fb;
static uint8_t *s_ink;

void jo_ink_begin(const uint8_t *fb, uint8_t *ink)
{
    s_ink_fb = fb;
    s_ink = ink;
    if (s_ink)
        memset(s_ink, 0, (size_t)jo_gw * (size_t)jo_gh);
}

void jo_ink_end(void)
{
    s_ink_fb = NULL;
    s_ink = NULL;
}

void jo_tag(int id, int x, int y, int w, int h)
{
    if (!s_ink || id == JO_INK_NONE)
        return;
    for (int j = jo_clampi(y, 0, jo_gh); j < jo_clampi(y + h, 0, jo_gh); j++)
        for (int i = jo_clampi(x, 0, jo_gw); i < jo_clampi(x + w, 0, jo_gw); i++)
            if (jo_get(s_ink_fb, i, j))
                s_ink[j * jo_gw + i] = (uint8_t)id;
}

void jo_untag(int x, int y, int w, int h)
{
    if (!s_ink)
        return;
    for (int j = jo_clampi(y, 0, jo_gh); j < jo_clampi(y + h, 0, jo_gh); j++)
        for (int i = jo_clampi(x, 0, jo_gw); i < jo_clampi(x + w, 0, jo_gw); i++)
            s_ink[j * jo_gw + i] = 0;
}

void jo_ink_lit_only(void)
{
    if (!s_ink)
        return;
    for (int j = 0; j < jo_gh; j++)
        for (int i = 0; i < jo_gw; i++)
            if (!jo_get(s_ink_fb, i, j))
                s_ink[j * jo_gw + i] = 0;
}
