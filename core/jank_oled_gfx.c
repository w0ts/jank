/* The OLED UI's drawing primitives and font (the emulator's px, rect, frame, xorCol, text, textR, textC, icon, FONT_SRC),
 * and the JavaScript number rules the screens' text depends on (Math.round, toFixed). */
#include "jank_oled_int.h"
#include <math.h>
#include <stdio.h>
#include <string.h>

double jo_round(double x)
{
    double r = floor(x);
    return x - r >= 0.5 ? r + 1.0 : r;          /* x - floor(x) is exact for every double */
}

/* n = |x| * 10^digits rounded half up, exactly: |x| = m * 2^e with m an integer of 53 bits */
static uint64_t scaled(double ax, int digits, int *ok)
{
    static const uint64_t P10[4] = {1, 10, 100, 1000};
    int e = 0, sh;
    double f;
    uint64_t m, big;
    *ok = isfinite(ax);
    if (!*ok || ax == 0.0)
        return 0;
    f = frexp(ax, &e);                           /* ax = f * 2^e, f in [0.5, 1) */
    m = (uint64_t)ldexp(f, 53);                  /* ax = m * 2^(e - 53), exactly */
    sh = 53 - e;
    big = m * P10[digits];                       /* < 2^63: m < 2^53, 10^3 < 2^10 */
    if (sh < 0) {                                /* ax >= 2^53: beyond any value the screens show */
        *ok = 0;
        return 0;
    }
    if (sh == 0)
        return big;
    if (sh > 63)                                /* ax < 2^-10: ax * 10^3 < 1, rounds to 0 */
        return ax * (double)P10[digits] >= 0.5 ? 1u : 0u;
    {
        uint64_t n = big >> sh, rem = big & ((1ull << sh) - 1u), half = 1ull << (sh - 1);
        return rem >= half ? n + 1u : n;
    }
}

void jo_fixed(double x, int digits, char *out, size_t cap)
{
    static const uint64_t P10[4] = {1, 10, 100, 1000};
    int ok;
    uint64_t n;
    if (digits < 0)
        digits = 0;
    if (digits > 3)
        digits = 3;
    n = scaled(fabs(x), digits, &ok);
    if (!ok) {                                   /* (beyond any value the screens show) */
        snprintf(out, cap, "%.*f", digits, x);
        return;
    }
    if (digits)
        snprintf(out, cap, "%s%llu.%0*llu", x < 0 ? "-" : "", (unsigned long long)(n / P10[digits]), digits,
                 (unsigned long long)(n % P10[digits]));
    else
        snprintf(out, cap, "%s%llu", x < 0 ? "-" : "", (unsigned long long)n);
}

int jo_gw = JO_W, jo_gh = JO_H;

void jo_px(uint8_t *fb, int x, int y, int v)
{
    uint8_t bit;
    if (x < 0 || x >= jo_gw || y < 0 || y >= jo_gh)
        return;
    bit = (uint8_t)(1u << (y & 7));
    if (v)
        fb[(y >> 3) * jo_gw + x] |= bit;
    else
        fb[(y >> 3) * jo_gw + x] &= (uint8_t)~bit;
}

void jo_xor_px(uint8_t *fb, int x, int y)
{
    if (x >= 0 && x < jo_gw && y >= 0 && y < jo_gh)
        fb[(y >> 3) * jo_gw + x] ^= (uint8_t)(1u << (y & 7));
}

void jo_rect(uint8_t *fb, int x, int y, int w, int h, int v)
{
    for (int j = 0; j < h; j++)
        for (int i = 0; i < w; i++)
            jo_px(fb, x + i, y + j, v);
}

void jo_frame(uint8_t *fb, int x, int y, int w, int h, int v)
{
    jo_rect(fb, x, y, w, 1, v);
    jo_rect(fb, x, y + h - 1, w, 1, v);
    jo_rect(fb, x, y, 1, h, v);
    jo_rect(fb, x + w - 1, y, 1, h, v);
}

void jo_xor_col(uint8_t *fb, int x, int y0, int y1)
{
    for (int y = y0; y <= y1; y++)
        jo_xor_px(fb, x, y);
}

