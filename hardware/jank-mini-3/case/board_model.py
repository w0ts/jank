"""Writes board_model.scad: every part of lcd2.kicad_pcb as a box for box.scad's collision check (read only on the
board). Board coordinates: x right, y DOWN from the board's top-left corner, z up from OUR BOARD'S TOP (0); the board
is 1.6 mm, so its bottom is z -1.6.
Top SMD parts: their courtyard, as tall as the package (TOP_H, from the parts' 3D models in ../lib/3d or the maker's
drawing). Bottom through-hole parts: their bodies from ../lib/3d's models (bboxes read 2026-11-19), the DINs' depth
left to box.scad (din_depth).   KiCad's python: board_model.py  (one LoadBoard per process)"""
import os
import sys

import pcbnew

HERE = os.path.dirname(os.path.abspath(__file__))
PCB = os.path.join(HERE, "..", "lcd2.kicad_pcb")
OUT = os.path.join(HERE, "board_model.scad")
O = 100.0             # make_board.OX / OY: the board's top-left corner in KiCad
T = 1.6               # board thickness

TOP_H = {             # package height above the board, mm (model bbox z max, ../lib/3d, or the maker's drawing)
    "C0402": 0.5, "R0402": 0.4, "C0603": 0.8, "R0603": 0.5, "C0805": 1.3, "R0805": 0.6, "R1206": 0.6,
    "RES-SMD_L6.4": 0.7, "IND-SMD_L2.0": 1.0, "SOT-23-6": 1.5, "SOT-23-3": 1.1, "SOT-23_": 1.1, "SOT-563": 0.6,
    "TSSOP-14": 1.2, "SMAF": 1.06, "SW-SMD": 1.55, "USB-C-TH_GCT_USB4085": 3.46,
    "PADS": 0.1, "SJ2C": 0.1, "R_TWIN": 0.6, "HOLE": 0.0,
}


def top_h(name: str) -> float:
    for k, v in TOP_H.items():
        if name.startswith(k):
            return v
    sys.exit(f"no height for {name}")


def bbox(fp, layers):
    xs, ys = [], []
    for g in fp.GraphicalItems():
        if g.GetLayer() in layers:
            r = g.GetBoundingBox()
            xs += [pcbnew.ToMM(r.GetLeft()) - O, pcbnew.ToMM(r.GetRight()) - O]
            ys += [pcbnew.ToMM(r.GetTop()) - O, pcbnew.ToMM(r.GetBottom()) - O]
    return min(xs), min(ys), max(xs), max(ys)


def bottom_boxes(ref: str, name: str, x: float, y: float, cy) -> list:
    """the body (and nose) of a bottom through-hole part, z below the board's bottom (-T); the DIN's depth is
    'D' (box.scad's din_depth)"""
    if name.startswith("AUDIO-TH_PJ307C"):       # BOOMELE PJ-307C: body 12 x 12.2 x 5.0, nose d 6 x 2.0, axis 2.5 down
        if cy[1] < 1.0:                           # mouth at the top edge (-y)
            m = cy[1] + 0.18
            return [("body", x - 6.0, m + 2.0, -T - 5.0, x + 6.0, m + 14.2, -T),
                    ("nose", x - 3.0, m, -T - 5.5, x + 3.0, m + 2.0, -T + 0.5)]
        m = cy[3] - 0.18                          # mouth at the bottom edge (+y)
        return [("body", x - 6.0, m - 14.2, -T - 5.0, x + 6.0, m - 2.0, -T),
                ("nose", x - 3.0, m - 2.0, -T - 5.5, x + 3.0, m, -T + 0.5)]
    if name.startswith("AUDIO-TH_PJ-320A"):      # PJ-320A: body 14.1 x 6.1 x 5.0, nose d 5 x 2.0, mouth +x
        m = x + 9.23
        return [("body", x - 4.87, y - 3.06, -T - 5.0, m - 2.0, y + 3.06, -T),
                ("nose", m - 2.0, y - 2.5, -T - 5.0, m, y + 2.5, -T)]
    if name.startswith("CONN-TH_DIN-504B"):      # DIN-504B-M10: front plate 20.9 wide at y - 8.61, back y + 6.69
        return [("body", x - 10.45, y - 8.61, "D", x + 10.45, y + 6.69, -T)]
    if name.startswith("HDR-TH_14P"):             # J15 / J16: Kinghelm C2905490 male row, 2.5 mm plastic under us
        return [("plastic", x - 17.78, y - 1.27, -T - 2.5, x + 17.78, y + 1.27, -T)]
    sys.exit(f"no body for bottom part {ref} {name}")


def main() -> None:
    b = pcbnew.LoadBoard(PCB)
    rows = []
    for fp in sorted(b.GetFootprints(), key=lambda f: f.GetReference()):
        ref, name = fp.GetReference(), str(fp.GetFPID().GetLibItemName())
        x, y = pcbnew.ToMM(fp.GetPosition().x) - O, pcbnew.ToMM(fp.GetPosition().y) - O
        if fp.IsFlipped():
            cy = bbox(fp, (pcbnew.B_CrtYd,))
            for part, x0, y0, z0, x1, y1, z1 in bottom_boxes(ref, name, x, y, cy):
                rows.append((ref, "B", part, x0, y0, z0, x1, y1, z1))
        else:
            h = top_h(name)
            if h <= 0.0:
                continue
            x0, y0, x1, y1 = bbox(fp, (pcbnew.F_CrtYd,))
            rows.append((ref, "F", name.split("_")[0], x0, y0, 0.0, x1, y1, h))
    with open(OUT, "w") as f:
        f.write("// SPDX-License-Identifier: GPL-3.0-only\n// GENERATED by board_model.py from ../lcd2.kicad_pcb: do not edit.\n")
        f.write("// [ref, side, what, x0, y0, z0, x1, y1, z1]: board mm, y DOWN, z up from our board's top; \"D\" = -1.6 - din_depth\n")
        f.write("BOARD_PARTS = [\n")
        for r in rows:
            v = [f"{c:.3f}" if isinstance(c, float) else (f'"{c}"' if c != "D" else "-1.6 - din_depth") for c in r]
            f.write("    [" + ", ".join(v) + "],\n")
        f.write("];\n")
    print(f"{len(rows)} boxes -> {OUT}")


if __name__ == "__main__":
    main()
