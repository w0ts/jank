"""An estimate of what an assembled jank tiny costs at JLCPCB, both variants (two-sided "tiny", one-sided "tiny-1s"),
at 5 and 30 boards, from the parts snapshot (fab/parts-snapshot.json, jlc_parts.py) and the assembly summaries
(fab/summary.json, fab/1s/summary.json, make_assembly.py). Writes fab/cost.md. Nothing here is a quote: the fees are
the ones seen in earlier JLCPCB quotes for the jank boards or JLC's published rules, all marked so; get a real quote.

  python3 cost.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
FEES = {   # USD; where each figure comes from
    "econ_setup": (8.24, "Economic setup fee, seen in the jank-pcb-mod quote 2026-11-09"),
    "econ_stencil": (1.55, "Economic stencil, same quote"),
    "nitrogen": (0.91, "nitrogen reflow, same quote (JLC added it; may be optional)"),
    "std_fixed": (85.0, "Standard (two-sided) assembly fixed fees, JLCPCB's quote for the jank board 2026-11-08 (hardware/pcb/README)"),
    "extended": (3.0, "per unique Extended part per order (JLCPCB's published rule; the 2026-11-09 quote's $21.63 fits ~7 lines); preferred Extended parts are exempt"),
    "joint": (0.0017, "per solder joint (JLCPCB's published rate; UNVERIFIED for Standard)"),
    "pcb_5": (3.30, "bare 2-layer board, 5 pieces, as in the 2026-11-09 quote (a larger board; UNVERIFIED for this size)"),
    "pcb_30": (8.00, "bare 2-layer board, 30 pieces: an ESTIMATE, not seen in a quote"),
}


def unit_price(prices, qty):
    best = prices[0][1]
    for start, p in prices:
        if qty >= start:
            best = p
    return best


def estimate(summary, snap, n):
    parts = 0.0
    for code, per_board in summary["qty"].items():
        s = snap["parts"][code]
        qty = per_board * n + s["loss"]
        parts += qty * unit_price(s["prices"], qty)
    ext = [c for c in summary["qty"] if snap["parts"][c]["type"] == "Extended" and not snap["parts"][c]["preferred"]]
    two = summary["sides"] == ["Bottom", "Top"]
    fixed = FEES["std_fixed"][0] if two else FEES["econ_setup"][0] + FEES["econ_stencil"][0] + FEES["nitrogen"][0]
    rows = {
        "PCB (bare)": FEES["pcb_5" if n <= 5 else "pcb_30"][0],
        "assembly fixed fees" + (" (Standard, two sides)" if two else " (Economic, one side)"): fixed,
        f"Extended parts fee ({len(ext)} lines)": len(ext) * FEES["extended"][0],
        f"solder joints ({summary['joints']} a board)": summary["joints"] * n * FEES["joint"][0],
        "parts (with JLC's loss)": parts,
    }
    total = sum(rows.values())
    return rows, total


def main():
    snap = json.load(open(os.path.join(HERE, "fab", "parts-snapshot.json")))
    out = [f"# jank tiny: cost estimate (generated by cost.py; parts snapshot {snap['date']})", "",
           "Shipping, taxes and the case are not included. Every figure is an estimate (see the sources below).", ""]
    for label, path in (("two-sided, tiny (the board)", "fab/summary.json"), ("one-sided, tiny-1s", "fab/1s/summary.json")):
        s = json.load(open(os.path.join(HERE, path)))
        w, h = s["board_mm"]
        out += [f"## {label}: {w:g} x {h:g} mm ({w * h:.0f} mm2), {s['parts']} parts on {s['lines']} lines, {s['joints']} joints, "
                f"{' + '.join(s['sides'])}", "", "| | 5 boards | 30 boards |", "|---|---|---|"]
        r5, t5 = estimate(s, snap, 5)
        r30, t30 = estimate(s, snap, 30)
        for k in r5:
            k30 = [x for x in r30 if x.split(" (")[0] == k.split(" (")[0]][0]
            out.append(f"| {k} | {r5[k]:.2f} | {r30[k30]:.2f} |")
        out += [f"| **total** | **{t5:.2f}** | **{t30:.2f}** |", f"| **per board** | **{t5 / 5:.2f}** | **{t30 / 30:.2f}** |", ""]
    out += ["## Sources of the fees", ""] + [f"- {k}: USD {v:g}, {why}" for k, (v, why) in FEES.items()]
    open(os.path.join(HERE, "fab", "cost.md"), "w").write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
